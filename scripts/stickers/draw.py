def grow(pts, d):                                                         # offset a closed polygon outward by d
    n=len(pts); A=sum(pts[i][0]*pts[(i+1)%n][1]-pts[(i+1)%n][0]*pts[i][1] for i in range(n)); sg=1 if A>0 else -1
    res=[]
    for i in range(n):
        (x0,y0),(x1,y1),(x2,y2)=pts[i-1],pts[i],pts[(i+1)%n]
        nx,ny=0,0
        for ax,ay,bx,by in ((x0,y0,x1,y1),(x1,y1,x2,y2)):
            dx,dy=bx-ax,by-ay; L=math.hypot(dx,dy) or 1; nx+=dy/L; ny+=-dx/L
        L=math.hypot(nx,ny) or 1; res.append((x1+sg*d*nx/L, y1+sg*d*ny/L))
    return res
