def tube_pts(spine, prof):
    pts=resample(spine, False, 2); nm=normals(pts, False); n=len(pts)
    L=[(p[0]+v[0]*prof(i/(n-1)),p[1]+v[1]*prof(i/(n-1))) for i,(p,v) in enumerate(zip(pts,nm))]
    R=[(p[0]-v[0]*prof(i/(n-1)),p[1]-v[1]*prof(i/(n-1))) for i,(p,v) in enumerate(zip(pts,nm))]
    return L+R[::-1]

