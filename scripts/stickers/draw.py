def tube(spine, prof, amp=0.4):
    """solid along a centreline; prof(t) = half-width at t in 0..1"""
    pts=resample(spine, False, 3); nm=normals(pts, False); n=len(pts)
    L=[(p[0]+v[0]*prof(i/(n-1)),p[1]+v[1]*prof(i/(n-1))) for i,(p,v) in enumerate(zip(pts,nm))]
    R=[(p[0]-v[0]*prof(i/(n-1)),p[1]-v[1]*prof(i/(n-1))) for i,(p,v) in enumerate(zip(pts,nm))]
    s.blob(L+R[::-1], amp=amp)
def offset(spine, o, t0=0, t1=1):
    pts=resample(spine, False, 3); nm=normals(pts, False); n=len(pts)
    return [(p[0]+v[0]*o(i/(n-1)),p[1]+v[1]*o(i/(n-1))) for i,(p,v) in enumerate(zip(pts,nm)) if t0<=i/(n-1)<=t1][::3]

