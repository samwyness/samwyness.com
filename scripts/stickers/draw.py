def frame(pts, i):
    """point, unit tangent, unit normal at index i of a resampled line"""
    a=pts[max(i-1,0)]; b=pts[min(i+1,len(pts)-1)]; d=(b[0]-a[0],b[1]-a[1]); L=math.hypot(*d) or 1
    return pts[i], (d[0]/L,d[1]/L), (-d[1]/L,d[0]/L)

